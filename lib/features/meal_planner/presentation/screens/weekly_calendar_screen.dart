import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import '../../../../core/constants/app_colors.dart';
import '../../../../core/utils/turkish_formatters.dart';
import '../controllers/meal_plan_controller.dart';
import '../widgets/meal_slot_card.dart';
import '../../../recipes/domain/models/recipe.dart';
import '../../../recipes/presentation/controllers/recipe_controller.dart';
import '../../../../core/services/share_service.dart';

class WeeklyCalendarScreen extends ConsumerStatefulWidget {
  const WeeklyCalendarScreen({super.key});

  @override
  ConsumerState<WeeklyCalendarScreen> createState() => _WeeklyCalendarScreenState();
}

class _WeeklyCalendarScreenState extends ConsumerState<WeeklyCalendarScreen> {
  int _selectedDayIndex = 0; // 0 = Pazartesi, 6 = Pazar

  void _showRecipePickerModal(DateTime date, String mealType) {
    showModalBottomSheet(
      context: context,
      isScrollControlled: true,
      shape: const RoundedRectangleBorder(
        borderRadius: BorderRadius.vertical(top: Radius.circular(24)),
      ),
      builder: (ctx) {
        return Consumer(
          builder: (context, ref, _) {
            final recipesAsync = ref.watch(filteredRecipesProvider);

            return DraggableScrollableSheet(
              initialChildSize: 0.8,
              minChildSize: 0.5,
              maxChildSize: 0.95,
              expand: false,
              builder: (context, scrollController) {
                return Padding(
                  padding: const EdgeInsets.all(20),
                  child: Column(
                    crossAxisAlignment: CrossAxisAlignment.start,
                    children: [
                      Row(
                        mainAxisAlignment: MainAxisAlignment.spaceBetween,
                        children: [
                          Text(
                            '${TurkishFormatters.getDayName(date.weekday)} için Tarif Seç',
                            style: const TextStyle(fontSize: 18, fontWeight: FontWeight.bold),
                          ),
                          IconButton(
                            icon: const Icon(Icons.close),
                            onPressed: () => Navigator.pop(context),
                          ),
                        ],
                      ),
                      const SizedBox(height: 12),
                      Expanded(
                        child: recipesAsync.when(
                          data: (recipes) {
                            return ListView.separated(
                              controller: scrollController,
                              itemCount: recipes.length,
                              separatorBuilder: (_, __) => const Divider(height: 1),
                              itemBuilder: (context, index) {
                                final recipe = recipes[index];
                                return ListTile(
                                  contentPadding: const EdgeInsets.symmetric(vertical: 4),
                                  title: Text(
                                    recipe.title,
                                    style: const TextStyle(fontWeight: FontWeight.w600, fontSize: 15),
                                  ),
                                  subtitle: Text(
                                    '${recipe.category} • ${recipe.totalTimeMinutes} dk • ${recipe.baseServings} Kişilik',
                                    style: const TextStyle(color: AppColors.textSecondary, fontSize: 12),
                                  ),
                                  trailing: const Icon(Icons.add_circle, color: AppColors.primary),
                                  onTap: () {
                                    ref.read(weeklyMealPlanProvider.notifier).addRecipeToMeal(
                                          date: date,
                                          mealType: mealType,
                                          recipe: recipe,
                                          servings: recipe.baseServings,
                                        );
                                    Navigator.pop(context);
                                  },
                                );
                              },
                            );
                          },
                          loading: () => const Center(child: CircularProgressIndicator()),
                          error: (err, _) => Center(child: Text('Hata: $err')),
                        ),
                      ),
                    ],
                  ),
                );
              },
            );
          },
        );
      },
    );
  }

  void _showAutoGenerateDialog() {
    bool incBreakfast = true;
    bool incLunch = true;
    bool incDinner = true;

    showDialog(
      context: context,
      builder: (ctx) {
        return StatefulBuilder(
          builder: (context, setDialogState) {
            return AlertDialog(
              shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(20)),
              title: Row(
                children: const [
                  Icon(Icons.auto_awesome, color: AppColors.primary),
                  SizedBox(width: 8),
                  Text('Sihirli Menü Oluştur', style: TextStyle(fontSize: 18)),
                ],
              ),
              content: Column(
                mainAxisSize: MainAxisSize.min,
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [
                  const Text(
                    'Seçtiğiniz tercihlere, bütçenize ve mevsime göre 7 günlük dengeli haftalık menünüz tek dokunuşla hazırlansın.',
                    style: TextStyle(fontSize: 14, color: AppColors.textSecondary),
                  ),
                  const SizedBox(height: 16),
                  CheckboxListTile(
                    dense: true,
                    title: const Text('Kahvaltıları planla'),
                    value: incBreakfast,
                    activeColor: AppColors.primary,
                    onChanged: (v) => setDialogState(() => incBreakfast = v ?? true),
                  ),
                  CheckboxListTile(
                    dense: true,
                    title: const Text('Öğle yemeklerini planla'),
                    value: incLunch,
                    activeColor: AppColors.primary,
                    onChanged: (v) => setDialogState(() => incLunch = v ?? true),
                  ),
                  CheckboxListTile(
                    dense: true,
                    title: const Text('Akşam yemeklerini planla'),
                    value: incDinner,
                    activeColor: AppColors.primary,
                    onChanged: (v) => setDialogState(() => incDinner = v ?? true),
                  ),
                ],
              ),
              actions: [
                TextButton(
                  onPressed: () => Navigator.pop(context),
                  child: const Text('İptal'),
                ),
                ElevatedButton(
                  onPressed: () {
                    ref.read(weeklyMealPlanProvider.notifier).autoGenerateMenu(
                          includeBreakfast: incBreakfast,
                          includeLunch: incLunch,
                          includeDinner: incDinner,
                        );
                    Navigator.pop(context);
                    ScaffoldMessenger.of(context).showSnackBar(
                      const SnackBar(
                        content: Text('Haftalık menünüz başarıyla oluşturuldu! Afiyet olsun.'),
                        backgroundColor: AppColors.secondary,
                      ),
                    );
                  },
                  child: const Text('Menüyü Oluştur'),
                ),
              ],
            );
          },
        );
      },
    );
  }

  @override
  Widget build(BuildContext context) {
    final currentMonday = ref.watch(selectedWeekMondayProvider);
    final weekDays = TurkishFormatters.getWeekDays(currentMonday);
    final currentPlanAsync = ref.watch(weeklyMealPlanProvider);
    final selectedDate = weekDays[_selectedDayIndex];

    final weekRangeTitle =
        '${TurkishFormatters.formatDayMonth(weekDays.first)} - ${TurkishFormatters.formatDayMonth(weekDays.last)}';

    return Scaffold(
      appBar: AppBar(
        title: const Text('Haftalık Menüm'),
        actions: [
          IconButton(
            icon: const Icon(Icons.share_outlined),
            tooltip: 'WhatsApp ile Paylaş',
            onPressed: () {
              currentPlanAsync.whenData((plan) {
                ShareService.shareWeeklyMenuAsText(plan);
              });
            },
          ),
          IconButton(
            icon: const Icon(Icons.refresh),
            tooltip: 'Haftayı Temizle',
            onPressed: () {
              ref.read(weeklyMealPlanProvider.notifier).clearPlan();
            },
          ),
        ],
      ),
      body: Column(
        children: [
          // Hafta Gezinti Başlığı
          Container(
            padding: const EdgeInsets.symmetric(horizontal: 16, vertical: 8),
            color: AppColors.surface,
            child: Row(
              mainAxisAlignment: MainAxisAlignment.spaceBetween,
              children: [
                IconButton(
                  icon: const Icon(Icons.chevron_left),
                  onPressed: () {
                    ref.read(weeklyMealPlanProvider.notifier).shiftWeek(-1);
                  },
                ),
                Row(
                  children: [
                    const Icon(Icons.calendar_month, size: 18, color: AppColors.primary),
                    const SizedBox(width: 8),
                    Text(
                      weekRangeTitle,
                      style: const TextStyle(fontWeight: FontWeight.bold, fontSize: 16),
                    ),
                  ],
                ),
                IconButton(
                  icon: const Icon(Icons.chevron_right),
                  onPressed: () {
                    ref.read(weeklyMealPlanProvider.notifier).shiftWeek(1);
                  },
                ),
              ],
            ),
          ),

          // Sihirli Menü Banner Butonu
          Padding(
            padding: const EdgeInsets.symmetric(horizontal: 16, vertical: 10),
            child: Container(
              padding: const EdgeInsets.all(14),
              decoration: BoxDecoration(
                gradient: const LinearGradient(
                  colors: [AppColors.primary, AppColors.primaryDark],
                  begin: Alignment.topLeft,
                  end: Alignment.bottomRight,
                ),
                borderRadius: BorderRadius.circular(16),
                boxShadow: [
                  BoxShadow(
                    color: AppColors.primary.withOpacity(0.3),
                    blurRadius: 8,
                    offset: const Offset(0, 4),
                  ),
                ],
              ),
              child: Row(
                children: [
                  Container(
                    padding: const EdgeInsets.all(10),
                    decoration: BoxDecoration(
                      color: Colors.white.withOpacity(0.2),
                      shape: BoxShape.circle,
                    ),
                    child: const Icon(Icons.auto_awesome, color: Colors.white, size: 24),
                  ),
                  const SizedBox(width: 12),
                  Expanded(
                    child: Column(
                      crossAxisAlignment: CrossAxisAlignment.start,
                      children: const [
                        Text(
                          'Bu Hafta Ne Pişirsem?',
                          style: TextStyle(
                            color: Colors.white,
                            fontSize: 16,
                            fontWeight: FontWeight.bold,
                          ),
                        ),
                        SizedBox(height: 2),
                        Text(
                          'Tek tıkla 7 günlük dengeli menü oluştur',
                          style: TextStyle(color: Colors.white70, fontSize: 12),
                        ),
                      ],
                    ),
                  ),
                  ElevatedButton(
                    onPressed: _showAutoGenerateDialog,
                    style: ElevatedButton.styleFrom(
                      backgroundColor: Colors.white,
                      foregroundColor: AppColors.primary,
                      padding: const EdgeInsets.symmetric(horizontal: 14, vertical: 8),
                      textStyle: const TextStyle(fontSize: 13, fontWeight: FontWeight.bold),
                    ),
                    child: const Text('Oluştur'),
                  ),
                ],
              ),
            ),
          ),

          // 7 Gün Yatay Seçici Şerit (Pzt, Sal, Çar, Per, Cum, Cmt, Paz)
          SizedBox(
            height: 72,
            child: ListView.builder(
              scrollDirection: Axis.horizontal,
              padding: const EdgeInsets.symmetric(horizontal: 12),
              itemCount: 7,
              itemBuilder: (context, index) {
                final date = weekDays[index];
                final isSelected = _selectedDayIndex == index;
                final isToday = date.day == DateTime.now().day &&
                    date.month == DateTime.now().month &&
                    date.year == DateTime.now().year;

                return GestureDetector(
                  onTap: () => setState(() => _selectedDayIndex = index),
                  child: Container(
                    width: 54,
                    margin: const EdgeInsets.symmetric(horizontal: 4, vertical: 4),
                    decoration: BoxDecoration(
                      color: isSelected ? AppColors.primary : AppColors.surface,
                      borderRadius: BorderRadius.circular(14),
                      border: Border.all(
                        color: isSelected
                            ? AppColors.primary
                            : isToday
                                ? AppColors.secondary
                                : AppColors.border,
                        width: isToday ? 1.8 : 1.0,
                      ),
                      boxShadow: isSelected
                          ? [
                              BoxShadow(
                                color: AppColors.primary.withOpacity(0.3),
                                blurRadius: 6,
                                offset: const Offset(0, 3),
                              )
                            ]
                          : null,
                    ),
                    child: Column(
                      mainAxisAlignment: MainAxisAlignment.center,
                      children: [
                        Text(
                          TurkishFormatters.getShortDayName(date.weekday),
                          style: TextStyle(
                            fontSize: 12,
                            fontWeight: FontWeight.w600,
                            color: isSelected ? Colors.white70 : AppColors.textSecondary,
                          ),
                        ),
                        const SizedBox(height: 4),
                        Text(
                          '${date.day}',
                          style: TextStyle(
                            fontSize: 17,
                            fontWeight: FontWeight.bold,
                            color: isSelected ? Colors.white : AppColors.textPrimary,
                          ),
                        ),
                      ],
                    ),
                  ),
                );
              },
            ),
          ),
          const SizedBox(height: 8),

          // Seçili Günün Öğünleri
          Expanded(
            child: currentPlanAsync.when(
              data: (plan) {
                final breakfastItem = plan.getItem(selectedDate, 'breakfast');
                final lunchItem = plan.getItem(selectedDate, 'lunch');
                final dinnerItem = plan.getItem(selectedDate, 'dinner');
                final snackItem = plan.getItem(selectedDate, 'snack');

                return ListView(
                  padding: const EdgeInsets.symmetric(horizontal: 16, vertical: 8),
                  children: [
                    Row(
                      children: [
                        Text(
                          TurkishFormatters.getDayName(selectedDate.weekday),
                          style: const TextStyle(fontSize: 18, fontWeight: FontWeight.bold),
                        ),
                        const SizedBox(width: 8),
                        Text(
                          TurkishFormatters.formatDate(selectedDate),
                          style: const TextStyle(color: AppColors.textSecondary, fontSize: 14),
                        ),
                      ],
                    ),
                    const SizedBox(height: 12),

                    // Kahvaltı
                    MealSlotCard(
                      mealType: 'breakfast',
                      item: breakfastItem,
                      onAddMeal: () => _showRecipePickerModal(selectedDate, 'breakfast'),
                      onDeleteMeal: breakfastItem != null
                          ? () => ref
                              .read(weeklyMealPlanProvider.notifier)
                              .removeItem(breakfastItem.id)
                          : null,
                    ),

                    // Öğle Yemeği
                    MealSlotCard(
                      mealType: 'lunch',
                      item: lunchItem,
                      onAddMeal: () => _showRecipePickerModal(selectedDate, 'lunch'),
                      onDeleteMeal: lunchItem != null
                          ? () => ref
                              .read(weeklyMealPlanProvider.notifier)
                              .removeItem(lunchItem.id)
                          : null,
                    ),

                    // Akşam Yemeği
                    MealSlotCard(
                      mealType: 'dinner',
                      item: dinnerItem,
                      onAddMeal: () => _showRecipePickerModal(selectedDate, 'dinner'),
                      onDeleteMeal: dinnerItem != null
                          ? () => ref
                              .read(weeklyMealPlanProvider.notifier)
                              .removeItem(dinnerItem.id)
                          : null,
                    ),

                    // Ara Öğün / Tatlı
                    MealSlotCard(
                      mealType: 'snack',
                      item: snackItem,
                      onAddMeal: () => _showRecipePickerModal(selectedDate, 'snack'),
                      onDeleteMeal: snackItem != null
                          ? () => ref
                              .read(weeklyMealPlanProvider.notifier)
                              .removeItem(snackItem.id)
                          : null,
                    ),
                    const SizedBox(height: 24),
                  ],
                );
              },
              loading: () => const Center(child: CircularProgressIndicator()),
              error: (err, _) => Center(child: Text('Hata: $err')),
            ),
          ),
        ],
      ),
    );
  }
}
